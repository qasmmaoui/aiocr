# ── Regex avancés ─────────────────────────────────────────────────────────
_R1  = re.compile(r'امل([\u0600-\u06ff])')
_R2  = re.compile(r'اإل([\u0600-\u06ff])')
_R3  = re.compile(r'(?:^|(?<=\s))ال ([\u0600-\u06ff])', re.MULTILINE)
_R4  = re.compile(r'(مال)([\u0621-\u063a\u0641-\u064a])')
_R5  = re.compile(r'قغض([\u0600-\u06ff]?)')
_R6  = re.compile(r'ـ+')
_R7  = re.compile(r'(?<![^\s])(اال)([\u0600-\u06ff])')
_R8  = re.compile(r'(إ|ا)عال([\u0621-\u063a\u0641-\u064a])')
_R9  = re.compile(r'([\u0600-\u06ff]{3,})لا(?=[\s،؛.\n]|$)')
_R10 = re.compile(r'الا([\u0623\u0625\u0622\u0624\u0626])')
_R11 = re.compile(r'(?:^|(?<=[\s،؛:؟!\n]))أل([\u0600-\u06ff]+)', re.MULTILINE)
_R12 = re.compile(r'يهة(?=[\s،؛.\n\u060c\u061b]|$)')
_R13 = re.compile(r'(?<=[\u0600-\u06ff\s])[*+]{1,3}(?=[\u0600-\u06ff\s])')

_EXCEPTION_CHARS = set('مجياقو')

_ALLOWED_FORMS = frozenset({
    'إلا', 'ألا', 'وإلا', 'فإلا', 'بلا', 'هلا',
    'لولا', 'خلا', 'علا', 'جلا', 'حلا', 'غلا', 'ملا', 'تعلا',
})

_ALLOWED_VERBS = frozenset([
    'ألزم', 'ألزمت', 'ألزمه', 'ألزمها', 'ألزمهم',
    'ألغى', 'ألغت', 'ألغيت', 'ألغوا',
    'ألحق', 'ألحقت', 'ألحقه', 'ألقى', 'ألقت',
    'ألف', 'ألفا', 'ألوف', 'ألفاظ', 'ألفة',
    'ألوان', 'ألواح', 'ألعاب', 'ألغاز',
    'ألحان', 'ألياف', 'ألم', 'ألما',
    'ألبان', 'ألبسة', 'ألق', 'ألقاب',
])

# Ligatures المـ → الم
_LIGATURES = [
    (re.compile(r'(^|(?<=\s))' + re.escape(w)), r)
    for w, r in [
        ('اجل', 'الج'), ('احل', 'الح'), ('اخل', 'الخ'),
        ('ادل', 'الد'), ('اذل', 'الذ'), ('ارل', 'الر'),
        ('ازل', 'الز'), ('اسل', 'الس'), ('اشل', 'الش'),
        ('اصل', 'الص'), ('اضل', 'الض'), ('اطل', 'الط'),
        ('اظل', 'الظ'), ('اعل', 'الع'), ('اغل', 'الغ'),
        ('افل', 'الف'), ('اقل', 'الق'), ('اكل', 'الك'),
        ('انل', 'الن'), ('اول', 'الو'), ('ايل', 'الي'),
        ('دالخ', 'داخل'),
    ]
]


def correct_text(text: str) -> tuple[str, list[str]]:
    """
    Corrige le texte arabe issu de l'OCR.

    Returns:
        (texte_corrigé, liste_des_corrections_appliquées)
    """
    applied: list[str] = []

    # 0. Formes de présentation → arabe standard (avant toute heuristique)
    text = unicodedata.normalize("NFKC", text or "")

    # 1. Dictionnaire statique
    for wrong, right in OCR_DICT.items():
        if wrong in text:
            text = text.replace(wrong, right)
            applied.append(f"{wrong}→{right}")

    # 2. Kashida
    if 'ـ' in text:
        text = _R6.sub('', text)

    # 3. يهة → ية (fin de mot)
    if 'يهة' in text:
        text = _R12.sub('ية', text)

    # 4. Symboles parasites * +
    if '*' in text or '+' in text:
        text = _R13.sub(' ', text)

    # 5. اال → الا
    if 'اال' in text:
        text = _R7.sub(lambda m: 'الا' + m.group(2), text)
        text = text.replace(' اال', ' الا')

    # 6. لا en fin de mot
    if 'لا' in text:
        text = _R9.sub(
            lambda m: m.group(1) + 'لا'
            if len(m.group(1) + 'لا') < 5 or m.group(1) + 'لا' in _ALLOWED_FORMS
            else m.group(1) + 'ال',
            text,
        )

    # 7. احمل → المح
    if 'احمل' in text:
        text = text.replace('احمل', 'المح')

    # 8. امل → الم
    text = _R1.sub(lambda m: 'الم' + m.group(1), text)

    # 9. Ligatures
    for pat, rep in _LIGATURES:
        text = pat.sub(rep, text)

    # 10. واإل / باإل …
    for wrong, right in [
        ('واإل', 'والإ'), ('باإل', 'بالإ'),
        ('لإل', 'للإ'), ('فاإل', 'فالإ'), ('كاإل', 'كالإ'),
    ]:
        if wrong in text:
            text = text.replace(wrong, right)

    # 11. اإل → الإ
    text = _R2.sub(lambda m: 'الإ' + m.group(1), text)

    # 12. واأل / باأل …
    for wrong, right in [
        ('واأل', 'والأ'), ('باأل', 'بالأ'),
        ('لأل', 'للأ'), ('فاأل', 'فالأ'),
    ]:
        if wrong in text:
            text = text.replace(wrong, right)

    # 13. الا + همزة → ال + همزة
    if 'الا' in text:
        text = _R10.sub(lambda m: 'ال' + m.group(1), text)

    # 14. أل → الأ (sauf verbes connus)
    if 'أل' in text:
        text = _R11.sub(
            lambda m: 'أل' + m.group(1)
            if 'أل' + m.group(1) in _ALLOWED_VERBS
            else 'الأ' + m.group(1),
            text,
        )

    # 15. قغض → قض
    if 'قغض' in text:
        text = _R5.sub(lambda m: 'قض' + m.group(1), text)

    # 16. ال + espace + lettre → لا + lettre
    text = _R3.sub(r'لا \1', text)

    # 17. مال → ملا (sauf exceptions)
    text = _R4.sub(
        lambda m: m.group(0) if m.group(2) in ('ي', 'ك', 'و', 'ل') else 'ملا' + m.group(2),
        text,
    )

    # 18. عال → علا (sauf exceptions)
    if 'عال' in text:
        text = _R8.sub(
            lambda m: m.group(0) if m.group(2) in _EXCEPTION_CHARS else m.group(1) + 'علا' + m.group(2),
            text,
        )

    return text, applied
